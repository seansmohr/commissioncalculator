  /**
   * The rating area for a ZIP code in an area-rated state.
   * Returns a number, or null when the state is not area-rated, the ZIP is not
   * five digits, or the ZIP is not in any of that state's charts.
   */
  function areaForZip(state, zip) {
    var areas = ZIP_AREAS[state];
    if (!areas) { return null; }
    if (typeof zip !== 'string' && typeof zip !== 'number') { return null; }
    var text = String(zip).trim();
    if (!/^[0-9]{5}$/.test(text)) { return null; }
    var n = Number(text);
    var found = null;
    Object.keys(areas).forEach(function (area) {
      areas[area].forEach(function (range) {
        var dash = range.indexOf('-');
        var lo = dash === -1 ? Number(range) : Number(range.slice(0, dash));
        var hi = dash === -1 ? lo : Number(range.slice(dash + 1));
        if (n >= lo && n <= hi) { found = Number(area); }
      });
    });
    return found;
  }

